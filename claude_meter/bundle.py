"""Assemble a `Claude Meter.app` bundle around this checkout's virtualenv.

    python -m claude_meter.bundle ~/Applications

macOS identifies a process by the bundle its *executable* lives in. Run via the venv's
`python`, that executable ends up being Python.app's, so the Dock, Cmd-Tab and
notifications all say "Python". The bundle built here holds no copy of the code; its
Contents/MacOS/Claude Meter is a symlink to the real interpreter binary and its launcher
points that interpreter at this venv. The process then belongs to Claude Meter.app and
picks up the name, icon and LSUIElement setting from its Info.plist.
"""

import os
import plistlib
import shutil
import stat
import sys
from importlib.metadata import PackageNotFoundError, version
from pathlib import Path

APP_NAME = "Claude Meter"
BUNDLE_ID = "com.github.aki77.claude-meter"
LAUNCHER_NAME = "claude-meter"
ICON_PATH = Path(__file__).parent / "resources" / "AppIcon.icns"

LAUNCHER_TEMPLATE = """#!/bin/sh
# Generated by `python -m claude_meter.bundle`; re-run install.sh rather than editing.
#
# Runs the venv's interpreter *through this bundle* so macOS attributes the process to
# Claude Meter.app rather than to Python.app. __PYVENV_LAUNCHER__ is how CPython's own
# macOS stub tells the interpreter which venv it was launched from; the interpreter
# removes it from the environment once it has started.
export __PYVENV_LAUNCHER__={venv_python}
exec "$(cd "$(dirname "$0")" && pwd)/{app_name}" -m claude_meter "$@"
"""


def _version() -> str:
    try:
        return version("claude-meter")
    except PackageNotFoundError:
        return "0"


def interpreter_binary() -> Path:
    """The Mach-O that actually runs Python, bypassing any launcher stub.

    In a framework build (Homebrew, python.org) `bin/python3.x` is a tiny stub that
    execs Python.app/Contents/MacOS/Python; symlinking the stub would hand the process
    back to Python.app. Other builds (uv-managed, pyenv) have no stub.
    """
    framework = Path(sys.base_prefix) / "Resources" / "Python.app" / "Contents" / "MacOS" / "Python"
    if framework.exists():
        return framework
    return Path(os.path.realpath(sys._base_executable))


def info_plist(app_version: str) -> dict:
    return {
        "CFBundleName": APP_NAME,
        "CFBundleDisplayName": APP_NAME,
        "CFBundleIdentifier": BUNDLE_ID,
        "CFBundleExecutable": LAUNCHER_NAME,
        "CFBundleIconFile": "AppIcon",
        "CFBundlePackageType": "APPL",
        "CFBundleInfoDictionaryVersion": "6.0",
        "CFBundleShortVersionString": app_version,
        "CFBundleVersion": app_version,
        "LSMinimumSystemVersion": "11.0",
        # Start without a Dock tile; the app promotes itself to a regular app at launch
        # when "Show in Dock" is on. Doing it this way round avoids a Dock icon flashing
        # up on every start when the user has chosen to hide it.
        "LSUIElement": True,
        "NSHighResolutionCapable": True,
        "NSPrincipalClass": "NSApplication",
    }


def build(dest_dir: Path, venv_python: Path = Path(sys.executable)) -> Path:
    """Create (or replace) `<dest_dir>/Claude Meter.app`. Returns the bundle path."""
    app = dest_dir / f"{APP_NAME}.app"
    contents = app / "Contents"
    macos = contents / "MacOS"
    resources = contents / "Resources"
    if app.exists():
        shutil.rmtree(app)
    macos.mkdir(parents=True)
    resources.mkdir()

    with open(contents / "Info.plist", "wb") as fh:
        plistlib.dump(info_plist(_version()), fh)
    shutil.copyfile(ICON_PATH, resources / "AppIcon.icns")
    os.symlink(interpreter_binary(), macos / APP_NAME)

    launcher = macos / LAUNCHER_NAME
    launcher.write_text(
        LAUNCHER_TEMPLATE.format(venv_python=_shell_quote(str(venv_python)), app_name=APP_NAME)
    )
    launcher.chmod(launcher.stat().st_mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    # Launch Services caches bundle metadata by path; a fresh mtime makes it re-read.
    app.touch()
    return app


def _shell_quote(value: str) -> str:
    return "'" + value.replace("'", "'\\''") + "'"


def main(argv: list[str] = sys.argv[1:]) -> None:
    if len(argv) != 1:
        print("usage: python -m claude_meter.bundle DEST_DIR", file=sys.stderr)
        raise SystemExit(2)
    print(build(Path(argv[0]).expanduser()))


if __name__ == "__main__":
    main()
